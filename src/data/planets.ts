export const PLANET_BY_ID: Record<BodyId, Planet> = PLANETS.reduce(
  (acc, planet) => {
    acc[planet.id] = planet;
    return acc;
  },
  {} as Record<BodyId, Planet>,
);

export const PLANET_ORDER: BodyId[] = PLANETS.filter((p) => p.id !== "sun")
  .sort((a, b) => a.order - b.order)
  .map((p) => p.id);

/** Every body that can be the target of a mission (everything but the Sun). */
export const DESTINATION_PLANETS: Planet[] = PLANETS.filter((planet) => planet.id !== "sun");

/** The identifiers of every valid destination. */
export const DESTINATION_IDS: DestinationId[] = DESTINATION_PLANETS.map(
  (planet) => planet.id as DestinationId,
);

/** True when a body can be the target of a mission (everything but the Sun). */
export function isDestination(id: BodyId): id is DestinationId {
  return id !== "sun";
}

export function getPlanet(id: BodyId): Planet {
  return PLANET_BY_ID[id];
}

